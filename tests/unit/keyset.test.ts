import { describe, expect, it } from "vitest";
import { isRealDate, isRealTimestamp } from "@/lib/keyset";

describe("isRealDate", () => {
  it.each(["2024-02-29", "2000-02-29", "2026-04-30", "2026-12-31", "1970-01-01", "2100-12-31"])("실제 날짜는 받는다: %s", (value) => {
    expect(isRealDate(value)).toBe(true);
  });

  it.each([
    ["빈 값", ""],
    ["형식이 다름", "2026/05/01"],
    ["달이 없음", "2026-13-01"],
    ["일이 0", "2026-05-00"],
    // JS Date는 아래 값을 다음 달로 밀어 받아들인다. DB의 `::date`는 거절한다.
    ["2월 30일", "2026-02-30"],
    ["30일까지인 달의 31일", "2026-04-31"],
    ["윤년이 아닌 해의 2월 29일", "2023-02-29"],
    ["0000년(DB에 없는 해)", "0000-01-01"],
    ["DB가 받는 범위 아래", "1969-12-31"],
    ["DB가 받는 범위 위", "2101-01-01"],
    ["뒤에 덧붙인 값", "2026-05-01 00:00:00"],
  ])("올바르지 않은 값은 거절한다: %s", (_name, value) => {
    expect(isRealDate(value)).toBe(false);
  });
});

describe("isRealTimestamp", () => {
  it.each([
    "2026-11-14 07:21:34+00",
    "2026-11-14 07:21:34.123456+00",
    "2026-11-14 16:21:34.5+09",
    "2026-11-14 16:21:34.123456+09:00",
    "2024-02-29 00:00:00+00",
    "2026-12-31 23:59:59.999999-03:30",
    "2026-01-01 00:00:00.000001+14",
    "2026-11-14 07:21:34-08",
  ])("PostgreSQL이 내는 시각은 받는다: %s", (value) => {
    expect(isRealTimestamp(value)).toBe(true);
  });

  it.each([
    ["빈 값", ""],
    ["날짜만", "2026-11-14"],
    ["T 구분자", "2026-11-14T07:21:34+00"],
    ["오프셋 없음", "2026-11-14 07:21:34"],
    ["13월", "2026-13-14 07:21:34+00"],
    ["2월 30일", "2026-02-30 07:21:34+00"],
    ["25시", "2026-11-14 25:21:34+00"],
    ["24시", "2026-11-14 24:00:00+00"],
    ["60분", "2026-11-14 07:60:34+00"],
    ["60초", "2026-11-14 07:21:60+00"],
    ["오프셋 99시간", "2026-11-14 07:21:34+99"],
    ["오프셋 16시간", "2026-11-14 07:21:34+16"],
    ["오프셋 분 99", "2026-11-14 07:21:34+09:99"],
    ["0000년", "0000-11-14 07:21:34+00"],
    ["SQL을 흉내 낸 값", "2026-11-14 07:21:34+00'; drop table game_reviews;--"],
  ])("올바르지 않은 시각은 거절한다: %s", (_name, value) => {
    expect(isRealTimestamp(value)).toBe(false);
  });
});
